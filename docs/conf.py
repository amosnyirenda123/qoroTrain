# -- Source file headers -----------------------------------------------------------

_RULE = re.compile(r"^=+\s*$")
_FIELD = re.compile(r"^(Author|Date|Last Updated|File):\s*(.*)$")


def _render_header(app, what, name, obj, options, lines: list[str]) -> None:
    """Turn the project's file-header banner into reStructuredText before Napoleon runs.

    Every source file starts with a docstring of the form::

        =====
        Author: ...
        Date: ...
        Last Updated: ...
        File: ...

        Description:
            <module documentation>

        =====

    The ``=====`` rules would be read as section adornments, which docutils
    rejects inside a docstring. This hook removes the rules, renders
    Author / Date / Last Updated / File as a compact field list at the end of
    the page, and un-indents the Description body so that Napoleon parses it
    like any other docstring.
    """
    if what != "module" or not lines or not any(_RULE.match(line) for line in lines[:2]):
        return
    fields: list[str] = []
    body: list[str] = []
    in_description = False
    for line in lines:
        if _RULE.match(line):
            continue
        if not in_description:
            match = _FIELD.match(line)
            if match:
                fields.append(f":{match.group(1)}: {match.group(2)}")
            elif line.strip() == "Description:":
                in_description = True
            continue
        body.append(line[4:] if line.startswith("    ") else line)
    while body and not body[-1].strip():
        body.pop()
    lines[:] = body + ([""] + fields if fields else [])


def _public_bases(app, name, obj, options, bases: list) -> None:
    """Show ``pydantic.BaseModel`` instead of the private ``_Model`` base of the schema classes."""
    for i, base in enumerate(bases):
        if getattr(base, "__name__", "") == "_Model":
            bases[i] = base.__bases__[0]


def setup(app):
    """Register the docstring hooks; the header hook runs ahead of Napoleon (priority 500)."""
    app.connect("autodoc-process-docstring", _render_header, priority=400)
    app.connect("autodoc-process-bases", _public_bases)
